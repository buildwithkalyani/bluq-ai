// =============================================================================
// BLUQ TUNNEL TASK LIBRARY
// =============================================================================
// Sources: IRC:SP-91 (Road Tunnels), Railway Board Tunnel Manual, IS 5878,
//          NATM guidelines (ITA/ITA-AITES), DGMS safety regulations,
//          MoRTH Specifications, CPWD DSR, NDMA tunnel guidelines.
//
// Covers:
//   road_tunnel           — Road / highway tunnel (NATM, cut-and-cover, drill & blast)
//   railway_tunnel        — Railway tunnel through hills (NATM / drill & blast)
//   water_conveyance_tunnel — Irrigation / hydropower / water supply pressure tunnel
//
// Key tunnel constraints:
//   - NATM face advance rate governed by rock class (I=fast, V=very slow)
//   - TBM procurement: 540–730 days lead time — the single longest lead item
//   - DGMS approval mandatory for all drill-and-blast tunnels
//   - MoRTH / Railway Board design sanction required before excavation starts
//   - Monsoon causes portal stability issues and drainage overload
//   - Twin-tube tunnels require emergency cross-passages every 250–300m (IRC:SP-91)
// =============================================================================

